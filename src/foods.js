export const FOOD_IDS = Object.keys(FOODS);

export function nutritionOf(ingredient) {
  const known = FOODS[ingredient.food];
  const [kcal, protein, fat, carbs] = known ?? [
    ingredient.per100?.kcal ?? 0,
    ingredient.per100?.protein ?? 0,
    ingredient.per100?.fat ?? 0,
    ingredient.per100?.carbs ?? 0,
  ];
  const share = (ingredient.grams ?? 0) / 100;
  return {
    kcal: kcal * share,
    protein: protein * share,
    fat: fat * share,
    carbs: carbs * share,
    known: !!known,
  };
}
